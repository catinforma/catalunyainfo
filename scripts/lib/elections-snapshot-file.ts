/**
 * The generated `src/lib/programmatic/elections/snapshot.ts`, written the
 * same way by both scripts that touch it: `elections-snapshot.ts` (the
 * Generalitat and Idescat data) and `elections-29n.ts` (the Interior
 * Ministry's 29 Nov 2026 file).
 */
import { join } from "node:path";

import type { ElectionsSnapshot } from "../../src/lib/programmatic/elections/types.ts";

export const SNAPSHOT_FILE = join(import.meta.dirname, "..", "..", "src", "lib", "programmatic", "elections", "snapshot.ts");

export function renderSnapshotFile(snapshot: ElectionsSnapshot): string {
  return [
    "// GENERATED by scripts/elections-snapshot.ts from the official sources listed in",
    "// `sources` below. Do not edit by hand: re-run the script.",
    ...(snapshot.general2026 ? ["// `general2026` and each town's `g2026`: scripts/elections-29n.ts (Interior Ministry file)."] : []),
    'import type { ElectionsSnapshot } from "./types";',
    "",
    `export const SNAPSHOT: ElectionsSnapshot = ${JSON.stringify(snapshot, null, 1)};`,
    "",
  ].join("\n");
}

/**
 * Carries the 29N import over a refresh of the Generalitat data, so that
 * re-running `elections-snapshot.ts` never drops results already on the
 * pages. When a municipality now in the set has no imported result, the
 * refresh is refused unless `drop` is set (`--drop-29n`); the import is then
 * run again on the same official file.
 */
export function carryGeneral2026(previous: ElectionsSnapshot | null, next: ElectionsSnapshot, drop = false): ElectionsSnapshot {
  if (!previous?.general2026 || drop) return next;
  const byCode = new Map(previous.municipalities.map((m) => [m.code, m.g2026]));
  const missing = next.municipalities.filter((m) => !byCode.get(m.code)).map((m) => m.name);
  if (missing.length) {
    throw new Error(
      `the 29N results are imported, but ${missing.length} municipalities now in the set have none (${missing.slice(0, 5).join(", ")}). ` +
        "Re-run with --drop-29n, then `npm run elections:29n -- import <the same file>`.",
    );
  }
  return {
    ...next,
    municipalities: next.municipalities.map((m) => ({ ...m, g2026: byCode.get(m.code)! })),
    general2026: previous.general2026,
  };
}
